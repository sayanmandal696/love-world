/* =========================================
   ENTER LOVE WORLD
========================================= */

function enterLoveWorld() {

    const input =
        document.getElementById("nameInput");

    const name =
        input.value.trim();


    /* Check empty name */

    if (name === "") {

        input.style.borderColor = "#ff5c91";

        input.placeholder =
            "Please enter your name ♡";

        input.focus();

        return;
    }


    /* Store name */

    currentUser = name;


    /* Display name */

    const userName =
        document.getElementById("userName");

    if (userName) {

        userName.textContent =
            currentUser;

    }


    /* Change screen */

    const welcomeScreen =
        document.getElementById(
            "welcomeScreen"
        );

    const loveScreen =
        document.getElementById(
            "loveScreen"
        );


    welcomeScreen.classList.remove(
        "active"
    );


    loveScreen.classList.add(
        "active"
    );


    /* Create first moment */

    newMoment();


    /* Start music */

    startMusic();


    /* Start floating symbols */

    if (!floatingStarted) {

        startFloatingSymbols();

        floatingStarted = true;

    }

}


/* =========================================
   RANDOM NAME
========================================= */

function getRandomName() {

    let randomName;

    let attempts = 0;


    do {

        randomName =
            romanticNames[
                Math.floor(
                    Math.random() *
                    romanticNames.length
                )
            ];

        attempts++;

    } while (

        randomName.toLowerCase() ===
        currentUser.toLowerCase()

        &&

        attempts < 20

    );


    return randomName;

}


