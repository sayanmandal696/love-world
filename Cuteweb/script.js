/* =========================================
   ROMANTIC MUSIC
========================================= */

function startMusic() {

    /* Don't create music twice */

    if (musicPlaying) {

        return;

    }


    /* Create AudioContext */

    const AudioContext =
        window.AudioContext ||
        window.webkitAudioContext;


    if (!AudioContext) {

        console.log(
            "Web Audio API is not supported."
        );

        return;

    }


    audioContext =
        new AudioContext();


    /* Main volume */

    gainNode =
        audioContext.createGain();


    gainNode.gain.value =
        0.07;


    gainNode.connect(
        audioContext.destination
    );


    musicPlaying = true;


    /* Change button */

    const button =
        document.getElementById(
            "musicButton"
        );


    if (button) {

        button.textContent =
            "❚❚";

    }


    /* Start melody */

    playMelody();

}


/* =========================================
   ROMANTIC MELODY
========================================= */

function playMelody() {

    if (!musicPlaying) {

        return;

    }


    const melody = [

        261.63,
        329.63,
        392.00,
        329.63,

        293.66,
        349.23,
        440.00,
        349.23,

        261.63,
        329.63,
        392.00,
        523.25,

        392.00,
        329.63,
        293.66,
        261.63

    ];


    let index = 0;


    function nextNote() {

        if (!musicPlaying) {

            return;

        }


        const frequency =
            melody[index];


        /* Create oscillator */

        oscillator =
            audioContext.createOscillator();


        /* Create volume for note */

        const noteGain =
            audioContext.createGain();


        /* Soft piano-like sound */

        oscillator.type =
            "sine";


        oscillator.frequency.value =
            frequency;


        /* Fade in */

        noteGain.gain.setValueAtTime(
            0,
            audioContext.currentTime
        );


        noteGain.gain.linearRampToValueAtTime(
            0.12,
            audioContext.currentTime + 0.05
        );


        /* Fade out */

        noteGain.gain.exponentialRampToValueAtTime(
            0.001,
            audioContext.currentTime + 0.65
        );


        /* Connect */

        oscillator.connect(
            noteGain
        );


        noteGain.connect(
            gainNode
        );


        /* Play */

        oscillator.start();


        oscillator.stop(
            audioContext.currentTime +
            0.7
        );


        /* Next note */

        index++;


        if (
            index >=
            melody.length
        ) {

            index = 0;

        }


        musicTimer =
            setTimeout(
                nextNote,
                700
            );

    }


    nextNote();

}


/* =========================================
   PLAY / PAUSE MUSIC
========================================= */

function toggleMusic() {

    /* If music is stopped */

    if (!musicPlaying) {

        startMusic();

        return;

    }


    /* Stop music */

    musicPlaying = false;


    clearTimeout(
        musicTimer
    );


    /* Stop current note */

    if (oscillator) {

        try {

            oscillator.stop();

        } catch (error) {

            /* Already stopped */

        }

    }


    /* Change button */

    const button =
        document.getElementById(
            "musicButton"
        );


    if (button) {

        button.textContent =
            "▶";

    }

}


